#!/usr/bin/env python3
"""Writes src/i18n_table.rs: the Spanish of every sentence the window uses, copied from the
Console's own table (src/lib/i18n/es.ts). A sentence is whatever appears as t!("..."), tr("...") or
trf("...") in src/*.rs. A sentence with no entry in es.ts must be listed in tools/i18n-extra.json
(the few that only this window has); otherwise this script fails and nothing is written.

    python3 tools/gen-i18n.py          # rewrites src/i18n_table.rs
    python3 tools/gen-i18n.py --check  # fails if the file is out of date
"""
import json, pathlib, re, sys

here = pathlib.Path(__file__).resolve().parent.parent
ES = here.parent.parent / "src/lib/i18n/es.ts"


def js_string(text, i):
    """Reads a JS string literal at text[i] (quote ' " or `); returns (value, next index)."""
    q = text[i]
    i += 1
    out = []
    while text[i] != q:
        c = text[i]
        if c == "\\":
            i += 1
            c = text[i]
            if c == "n":
                out.append("\n")
            elif c == "u":
                out.append(chr(int(text[i + 1 : i + 5], 16)))
                i += 4
            else:
                out.append(c)
        else:
            out.append(c)
        i += 1
    return "".join(out), i + 1


def parse_es(text, name="ES"):
    start = text.index("export const " + name)
    i = text.index("{", text.index("=", start))
    i += 1
    table = {}
    while True:
        m = re.compile(r"\s*(//[^\n]*\n\s*|/\*.*?\*/\s*)*", re.S).match(text, i)
        i = m.end()
        if text[i] == "}":
            break
        if text.startswith("...", i):  # a spread of another area: those files are read below
            i = re.compile(r"\.\.\.[\w$]+\s*,?").match(text, i).end()
            continue
        if text[i] in "'\"`":
            key, i = js_string(text, i)
        else:
            m = re.compile(r"[A-Za-z_$][\w$]*").match(text, i)
            if not m:
                break  # a spread of another area ends the literal entries we can read
            key, i = m.group(0), m.end()
        i = re.compile(r"\s*:\s*").match(text, i).end()
        value, i = js_string(text, i)
        # `'a' + 'b'` concatenations
        while True:
            m = re.compile(r"\s*\+\s*").match(text, i)
            if not m:
                break
            part, i = js_string(text, m.end())
            value += part
        i = re.compile(r"\s*,?").match(text, i).end()
        table[key] = value
    return table


def used():
    found = {}
    pat = re.compile(r'\b(?:t!|trf|tr)\(\s*"((?:[^"\\]|\\.)*)"')
    for f in sorted((here / "src").glob("*.rs")):
        if f.name in ("i18n_table.rs", "i18n.rs"):
            continue
        for m in pat.finditer(f.read_text()):
            found[json.loads('"' + m.group(1) + '"')] = f.name
    return found


def rust(s):
    return json.dumps(s, ensure_ascii=False)


def main():
    es = parse_es(ES.read_text())
    for area in ("es-arsenal", "es-native", "es-configuration"):
        es.update(parse_es((ES.parent / (area + ".ts")).read_text(), "ES_AREA"))
    extra = json.loads((here / "tools/i18n-extra.json").read_text())
    rows, missing = [], []
    for en in sorted(used()):
        if en in es:
            rows.append((en, es[en]))
        elif en in extra:
            rows.append((en, extra[en]))
        else:
            missing.append(en)
    if missing:
        sys.exit("no Spanish in es.ts nor in tools/i18n-extra.json for:\n  " + "\n  ".join(missing))
    out = "// Generated by tools/gen-i18n.py from the Console's src/lib/i18n/es.ts. Do not edit.\n"
    out += "pub const ES: &[(&str, &str)] = &[\n"
    for en, sp in rows:
        out += f"    ({rust(en)}, {rust(sp)}),\n"
    out += "];\n"
    target = here / "src/i18n_table.rs"
    if "--check" in sys.argv:
        if not target.exists() or target.read_text() != out:
            sys.exit("src/i18n_table.rs is out of date: run tools/gen-i18n.py")
        return
    target.write_text(out)
    print(f"{len(rows)} sentences ({sum(1 for en, _ in rows if en not in es)} only in i18n-extra.json)")


main()
